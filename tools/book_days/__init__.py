"""book_days — сюжет страниц-дней книги «Марьям в Мире Кода», недели 7–29.

Каждый модуль weekNN.py описывает одну неделю курса словарём WEEK:
    num        — номер недели
    folder     — папка заготовок course/weekNN_*
    companion  — зверёнок-спутник недели (для подписи под обложкой)
    badge      — id SVG-символа героя из спрайта книги (pony/llama/alpaca/catP/catR/maryam)
    title      — тема недели (как в карте курса)
    lead       — подводка недели (1–3 предложения)
    days       — список дней: dict(day, theme, h3, seen, story, real, steps)
        theme  — короткая тема дня (плашка/кикер)
        h3     — заголовок страницы-дня
        seen   — что на картинке (уходит в alt изображения, если картинка есть)
        story  — абзацы прозы-рассказа, ≥1000 символов на день (правило книги):
                 живая сцена с героями → зверёнок объясняет идею → связь с игрой
        real   — пояснение к коду (тело врезки «🔬 Настоящее слово»),
                 ≥1000 символов на день; метафора → настоящий код игры
        steps  — шаги задания дня (2–3 пункта)

ПРАВИЛА КНИГИ (обязательны при любой правке контента):
  1. Объём на день: рассказ (story) ≥1000 символов + пояснение к коду (real)
     ≥1000 символов. Шрифт 12, ~1600 символов на две страницы.
  2. СКВОЗНОЙ СЮЖЕТ. Дни — одна непрерывная история, а не отдельные карточки.
     Марьям попала в Мир Кода через портал (день 1) и идёт по нему; спутники
     недель ведут её по очереди (пони По → лама Лу → альпака Аля → котики → …).
     Помнить, где героиня, что уже умеет, кто рядом, что было вчера и куда идём.
     Переходы связные: конец дня намекает на завтра, конец недели передаёт
     эстафету следующему спутнику. Перед правкой дня заглянуть в соседние дни.
  3. УВЛЕКАТЕЛЬНОСТЬ. Рассказ живой, а не служебный: диалоги, характеры героев,
     маленькая интрига/эмоция/открытие в каждом дне. Не повторять шаблонные фразы.
  4. Метод: по одному дню, написал → перечитал → сверил объём → дальше.
  5. Иллюстрации — забота отдельного агента; здесь про них не думать.

Диапазоны дней совпадают с tools/gen_course.py и tools/gen_image_prompts.py —
это источники правды по темам недель; иллюстрации будут рисоваться по промптам
из book/image-promt/, поэтому темы дней здесь согласованы с ними.

Загрузчик — load_weeks() — собирает все модули по возрастанию номера.
"""

import importlib
import pkgutil


def load_weeks():
    """Возвращает список словарей WEEK всех модулей weekNN по возрастанию."""
    weeks = []
    for info in pkgutil.iter_modules(__path__):
        if info.name.startswith("week"):
            mod = importlib.import_module(f"{__name__}.{info.name}")
            weeks.append(mod.WEEK)
    return sorted(weeks, key=lambda w: w["num"])


# Помощники разметки для текстов сюжета.
def M(s):
    """Моноширинный фрагмент кода."""
    return f'<span class="mono">{s}</span>'


def W(s):
    """Выделенный термин."""
    return f'<span class="word">{s}</span>'
