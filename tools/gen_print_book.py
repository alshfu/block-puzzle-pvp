def esc(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def page_cover() -> str:
    return """
<section class="page bleed">
  <img class="full" src="images/00_cover.jpg" alt="Обложка: Марьям и друзья у портала">
  <div class="cover-title">
    <p class="kicker">Код-РПГ · учебник-курс · 29 недель</p>
    <h1>Марьям<br>в Мире Кода</h1>
  </div>
</section>"""


def page_title() -> str:
    return """
<section class="page text">
  <p class="kicker">книга для печати</p>
  <h2>Марьям в Мире Кода</h2>
  <p class="lead">Как девочка, пони, лама, альпака и два котика построили настоящую игру BlockDuel 9×9 — и стали разработчиками.</p>
  <p>Читаем <b>неделю за неделей</b>. Сначала картинка: по ней видно тему. Потом одно дело вместе с папой. Вперёд не прыгаем.</p>
  <ul class="plain">
    <li>Неделя 1 — семь вечеров у портала</li>
    <li>Неделя 2 — коробочки-переменные</li>
    <li>Недели 3–29 — по одной теме, пока игра не заговорит на четырёх экранах</li>
  </ul>
  <p class="foot">Формат 210×210 мм · внутри настоящий код игры</p>
</section>"""


def page_heroes() -> str:
    cards = [
        ("01_maryam.jpg", "Марьям", "провалилась в игру и решила её построить"),
        ("02_pony_po.jpg", "Пони По", "коробочки и снимки истории"),
        ("03_llama_lu.jpg", "Лама Лу", "функции, числа, честная случайность"),
        ("04_alpaca_alya.jpg", "Альпака Аля", "если, повтори, фигуры, тесты"),
        ("05_cats.jpg", "Два котика", "списки, доска, бот и баги"),
    ]
    bits = []
    for img, name, cap in cards:
        bits.append(
            f'<figure><img src="images/{img}" alt="{name}"><figcaption><b>{name}</b>{cap}</figcaption></figure>'
        )
    return f"""
<section class="page text">
  <p class="kicker">герои</p>
  <h2>Кто идёт с нами</h2>
  <div class="heroes">{''.join(bits)}</div>
</section>"""


def page_art(src: str, alt: str, topic: str) -> str:
    return f"""
<section class="page art">
  <figure>
    <img src="images/{src}" alt="{esc(alt)}">
    <figcaption><span>Тема</span>{esc(topic)}</figcaption>
  </figure>
</section>"""


def page_text(kicker: str, title: str, seen: str, body: str, task: str) -> str:
    return f"""
<section class="page text">
  <p class="kicker">{esc(kicker)}</p>
  <h2>{esc(title)}</h2>
  <p class="seen"><b>Что видно:</b> {esc(seen)}</p>
  <p>{esc(body)}</p>
  <div class="task"><b>Вместе с папой.</b> {esc(task)}</div>
</section>"""


def build() -> str:
    parts = [CSS, page_cover(), page_title(), page_heroes()]

    parts.append("""
<section class="page text">
  <p class="kicker">неделя 1 · дни 1–7</p>
  <h2>Портал из блока</h2>
  <p class="lead">Семь вечеров. Ставим инструменты, открываем редактор, скачиваем игру, запускаем её и меняем слова на экране.</p>
  <p>Дальше — по одной странице на вечер. Книгу после задания закрываем.</p>
</section>""")
    for n, title, img, seen, task in DAYS1:
        parts.append(page_art(img, title, title))
        parts.append(page_text(f"день {n} · из 200", title, seen,
                               "Марьям входит в Мир Кода. Каждый вечер — один шаг.", task))

    parts.append("""
<section class="page text">
  <p class="kicker">неделя 2 · дни 8–14</p>
  <h2>Пони По и коробочки</h2>
  <p class="lead">Переменная — коробочка с подписью. В одной живут числа, в другой — буквы. Знак = значит «положи внутрь».</p>
</section>""")
    for n, title, img, seen, task in DAYS2:
        parts.append(page_art(img, title, title))
        parts.append(page_text(f"день {n} · из 200", title, seen,
                               "Пони По учит Марьям помнить данные.", task))

    for n, days, title, hero, topic, body, task in WEEKS:
        img = f"week{n:02d}.jpg"
        parts.append(page_art(img, title, topic))
        parts.append(page_text(
            f"неделя {n} · дни {days} · {hero}",
            title, topic, body, task))

    parts.append("""
<section class="page text">
  <p class="kicker">конец</p>
  <h2>Игра — ваша</h2>
  <p class="lead">Двести вечеров позади. Портал, коробочки, функции, доска, бот, сервер, четыре экрана.</p>
  <p>Ошибаться было можно. Именно из ошибок родилось мастерство.</p>
  <p class="foot">«Марьям в Мире Кода» · BlockDuel 9×9 · книга-сборник</p>
</section>""")

    return "<!DOCTYPE html>\n<html lang='ru'><head><meta charset='utf-8'>" \
        "<title>Марьям в Мире Кода — печать</title></head><body>\n" \
        + "\n".join(parts) + "\n</body></html>\n"


