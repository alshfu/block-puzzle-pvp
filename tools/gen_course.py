COMMENT = {"dart": "//", "ts": "//", "md": "", "bash": "#"}


def header(day, wnum, title, chapter, realfile, hint, task, is_project):
    """Строит шапку-комментарий файла-заготовки."""
    star = "🎯 МИНИ-ПРОЕКТ" if is_project else "Задание дня"
    return [
        f"КУРС «Марьям в Мире Кода» — День {day:03d} (Неделя {wnum}: {title})",
        f"Тема: {title}   ·   Глава книги: {chapter}",
        "",
        f"{star}:",
        f"  {task}",
        "",
        f"Связь с настоящей игрой: {realfile}",
        f"Подсказка: {hint}",
        "Правило дня: сначала подумай сам, потом загляни в настоящий код.",
    ]


def render(day, wnum, title, chapter, lang, realfile, hint, task, is_project):
    body = header(day, wnum, title, chapter, realfile, hint, task, is_project)
    bar = "═" * 66
    if lang == "md":
        out = [f"# День {day:03d} · Неделя {wnum}: {title}", ""]
        out += [f"**Тема:** {title}  ·  **Глава:** {chapter}", ""]
        out += [("### 🎯 Мини-проект" if is_project else "### Задание дня"), "", task, ""]
        out += [f"> Связь с игрой: `{realfile}`  ", f"> Подсказка: {hint}", ""]
        out += ["### ✍️ Мои заметки и шаги", "", "- [ ] ", "- [ ] ", "- [ ] ", "",
                "### 💭 Что я понял сегодня", "", "_(запиши своими словами)_", ""]
        return "\n".join(out) + "\n"
    c = COMMENT[lang]
    out = [f"{c} {bar}"]
    out += [f"{c} {ln}" if ln else c for ln in body]
    out += [f"{c} {bar}", ""]
    if lang in ("dart", "ts"):
        out += ["", f"{c} TODO: напиши здесь свой код 👇", "", "",
                "", f"{c} Когда готово — запусти и проверь результат."]
    else:  # bash
        out += ["", f"{c} TODO: впиши сюда свои команды 👇", "", "",
                f"{c} (выполняй по одной и смотри, что отвечает терминал)"]
    return "\n".join(out) + "\n"


def readme():
    lines = [
        "# 📚 Курс «Марьям в Мире Кода» — 200 дней заготовок",
        "",
        "Здесь на **каждый из 200 дней** лежит файл-заготовка: шапка с заданием",
        "дня, связью с настоящим кодом игры и местом `TODO`, куда ты дописываешь",
        "свой код. Идёшь по порядку — к концу собираешь и понимаешь **настоящую",
        "игру BlockDuel** (не с нуля, а меняя реальный проект).",
        "",
        "**Как работать:** открой файл дня → прочитай задание → сначала подумай",
        "сам → напиши код на месте `TODO` → запусти и проверь → загляни в",
        "настоящий файл игры (указан в шапке), сравни. Ошибаться — нормально!",
        "",
        "Иллюстрированный учебник, из которого этот курс, — отдельный документ",
        "(книга «Марьям в Мире Кода»). Файлы сгенерированы `tools/gen_course.py`.",
        "",
        "## Недели",
        "",
    ]
    for (wnum, d0, d1, slug, title, chapter, lang, *_rest) in WEEKS:
        lines.append(f"- **Неделя {wnum}** (дни {d0}–{d1}) — {title} · {chapter} → `{slug}/`")
    lines.append("")
    return "\n".join(lines) + "\n"


def main():
    base = os.path.join(ROOT, "course")
    count = 0
    for (wnum, d0, d1, slug, title, chapter, lang, realfile, hint, tasks) in WEEKS:
        wdir = os.path.join(base, slug)
        os.makedirs(wdir, exist_ok=True)
        days = list(range(d0, d1 + 1))
        for i, day in enumerate(days):
            is_project = (i == len(days) - 1)
            # Задание: по порядку; последний день недели — мини-проект (tasks[-1]),
            # остальные дни берут задания по кругу из tasks[:-1].
            if is_project:
                task = tasks[-1]
            else:
                task = tasks[i % (len(tasks) - 1)] if len(tasks) > 1 else tasks[0]
            content = render(day, wnum, title, chapter, lang,
                             realfile, hint, task, is_project)
            fname = f"day{day:03d}.{EXT[lang]}"
            with open(os.path.join(wdir, fname), "w", encoding="utf-8") as f:
                f.write(content)
            count += 1
    with open(os.path.join(base, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme())
    print(f"  course/ — {count} файлов-заготовок ({len(WEEKS)} недель) + README")
    assert count == 200, f"ожидалось 200 дней, вышло {count}"


if __name__ == "__main__":
    main()
